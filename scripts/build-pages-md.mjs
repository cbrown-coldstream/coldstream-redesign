// PAGES.md — the page inventory as markdown. Run: npm run pages (also a postbuild step).
//
// The page map (public/pagemap.html) and the handoff site (/handoff/) are the same information
// for a human in a browser. This is the version for a terminal, a diff and an LLM context window:
// no CSS, no JS, greppable, and small enough to paste.
//
// GENERATED. Every row is read out of dist/ and the redirect table. Do not hand-edit PAGES.md —
// the next build overwrites it, and in the meantime it is a document that describes a site that
// does not exist, which is worse than not having one.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve, join, relative } from "node:path";
import { MARKETS } from "../src/data/markets.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = resolve(root, "dist");
if (!existsSync(dist)) { console.error("  ✗ no dist/ — run npm run build first"); process.exit(1); }

const walk = (d) => readdirSync(d).flatMap((f) => {
  const p = join(d, f);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith("index.html") ? [p] : [];
});
const strip = (h) => h.replace(/<[^>]+>/g, " ").replace(/&amp;/g, "&").replace(/&#39;/g, "'")
  .replace(/&quot;/g, '"').replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();

const rules = readFileSync(resolve(root, "public/_redirects"), "utf8")
  .split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#")).map((l) => l.split(/\s+/));
const inbound = {};
for (const [, to] of rules) inbound[to] = (inbound[to] ?? 0) + 1;

const NAT_SVC = new Set(["roofing", "siding", "windows", "gutters", "commercial-roofing"]);
const lane = (url) => {
  const p = url.split("/").filter(Boolean);
  if (!p.length) return ["National home", "src/pages/index.astro"];
  if (p[0] in MARKETS) {
    if (p.length === 1) return ["Market landing", "src/pages/[market]/index.astro"];
    if (p[1] === "locations") return p.length === 2
      ? ["Locations index", "src/pages/[market]/locations/index.astro"]
      : ["Location area", "src/pages/[market]/locations/[area].astro"];
    if (p[1] === "about") return ["Market about", "src/pages/[market]/about.astro"];
    if (p[1] === "free-estimate") return ["Market convert", "src/pages/[market]/free-estimate.astro"];
    if (p[1] === "gallery") return ["Gallery", "src/pages/[market]/gallery.astro"];
    if (p[1] === "reviews") return ["Reviews", "src/pages/[market]/reviews.astro"];
    return p.length === 2
      ? ["Service hub", "src/pages/[market]/[service].astro"]
      : ["Sub-service", "src/pages/[market]/[hub]/[sub].astro"];
  }
  if (NAT_SVC.has(p[0])) return ["National service", "src/pages/[service].astro"];
  if (p[0] === "service-areas") return ["Service areas", "src/pages/service-areas.astro"];
  return ["Standalone", `src/pages/${p[0]}.astro`];
};

const pages = [];
for (const f of walk(dist)) {
  if (f.includes(`${"/handoff/"}`)) continue;
  let url = "/" + relative(dist, f).replace(/index\.html$/, "").replace(/\\/g, "/");
  if (url === "/./") url = "/";
  const h = readFileSync(f, "utf8");
  const body = h.replace(/<(script|style)[\s\S]*?<\/\1>/g, "");
  const [laneName, tpl] = lane(url);
  pages.push({
    url, lane: laneName, tpl,
    h1: strip(h.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1] ?? ""),
    words: strip(body).split(" ").length,
    noindex: /name="robots" content="noindex/.test(h),
    inbound: inbound[url] ?? 0,
    sections: [...body.matchAll(/<h2[^>]*>([\s\S]*?)<\/h2>/g)].map((m) => strip(m[1])).filter(Boolean),
  });
}
pages.sort((a, b) => a.url.localeCompare(b.url));

const marketOf = (u) => { const s = u.split("/")[1]; return s in MARKETS ? s : null; };
const groups = [["National / site-wide", (p) => !marketOf(p.url)],
                ...Object.entries(MARKETS).map(([slug, m]) => [m.name, (p) => marketOf(p.url) === slug])];

const laneRows = [...pages.reduce((m, p) => m.set(p.lane, [...(m.get(p.lane) ?? []), p]), new Map())]
  .sort((a, b) => b[1].length - a[1].length);

const N = (p) => (p.noindex ? "noindex" : "index");
const md = `# Pages

**${pages.length} pages** across **${laneRows.length} template lanes** · ${pages.filter((p) => !p.noindex).length} indexable ·
${pages.filter((p) => p.noindex).length} noindex · ${rules.length} redirect rules pointing into them.

> Generated by \`npm run pages\` from \`dist/\`. Do not hand-edit — the next build overwrites it.
> The same information with more detail is at \`/handoff/pages/\` and \`public/pagemap.html\`.

The live WordPress site this replaces has **443 URLs**. That is the whole point: the same copy on
a fifth of the pages, with every retired URL 301'd to whichever page absorbed it.

## Template lanes

A lane is the unit of work. Three markets are near-identical by design, so a change to a lane is a
change to every page in it.

| Pages | Lane | Template | Index | 301s in | Avg words |
|---:|---|---|---|---:|---:|
${laneRows.map(([l, v]) => {
  const idx = v.filter((p) => !p.noindex).length;
  return `| ${v.length} | ${l} | \`${v[0].tpl}\` | ${idx} / ${v.length - idx} noindex | ${v.reduce((n, p) => n + p.inbound, 0)} | ${Math.round(v.reduce((n, p) => n + p.words, 0) / v.length)} |`;
}).join("\n")}

## Every page

${groups.map(([label, test]) => {
  const rows = pages.filter(test);
  if (!rows.length) return "";
  const idx = rows.filter((p) => !p.noindex).length;
  return `### ${label} — ${rows.length} pages (${idx} indexable, ${rows.length - idx} noindex)

| URL | Lane | H1 | Words | 301s | Index |
|---|---|---|---:|---:|---|
${rows.map((p) => `| \`${p.url}\` | ${p.lane} | ${p.h1.replace(/\|/g, "\\|")} | ${p.words} | ${p.inbound || "—"} | ${N(p)} |`).join("\n")}`;
}).filter(Boolean).join("\n\n")}

## Section order per lane

What each template renders, in order. This is the page spec: rebuilding a page means producing
these sections with this copy.

${laneRows.map(([l, v]) => {
  const ex = v.find((p) => !p.noindex) ?? v[0];
  return `**${l}** — e.g. \`${ex.url}\`\n\n${ex.sections.map((s, i) => `${i + 1}. ${s}`).join("\n") || "_no h2 sections_"}`;
}).join("\n\n")}

## The noindex set, and what each is waiting on

${pages.filter((p) => p.noindex).map((p) => `- \`${p.url}\` — ${
  p.url.includes("/gallery/") ? "completed-job photos with consent recorded"
  : p.url.includes("/reviews/") ? "real, attributable, linkable Google reviews"
  : p.url === "/blog/" ? "a decision on which of the 48 WordPress posts migrate"
  : p.url === "/financing/" ? "a confirmed lender — every figure on it is gated until then"
  : p.url === "/thank-you/" ? "nothing. noindex permanently, by design"
  : p.url === "/about-us/" ? "founding year, ownership, crew size, markets-served history"
  : "legal review before indexing"
}`).join("\n")}
`;

writeFileSync(resolve(root, "PAGES.md"), md);
console.log(`  → PAGES.md — ${pages.length} pages, ${laneRows.length} lanes`);
