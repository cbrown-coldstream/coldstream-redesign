// THE SEO SURFACE — the signals that describe the BUSINESS rather than the page.
//
// Titles, descriptions and H1s are per-page and live with the page's own copy (data/pages/*,
// services.js, subservices.js). Everything here is site-wide: the entity nodes, the social-card
// defaults, and the robots directives. It exists because those were previously written inline in
// three templates, and three copies of an Organization node is three places for a phone number to
// go stale.
//
// ── WHAT ROUND 42 MEASURED AGAINST ───────────────────────────────────────────────────────────
//
// swordroof.com, the Cincinnati competitor round 41 already used for titles. Their home page ships
// one RoofingContractor node carrying `sameAs`, `openingHoursSpecification`, `priceRange`, a logo,
// an OfferCatalog of twelve services and 56 served places. Ours carried a name, a phone, an
// address and an areaServed list, and nothing else. The gap was not in the copy — it was in what
// the page told Google the business IS.
//
// TAKEN: sameAs, logo and image, the offer catalogue, the parent/child entity link, real
// telephone formatting, and the Open Graph completeness their WordPress plugin gives them free.
//
// REFUSED: `priceRange`, which they set to "$$$". It is a claim about what Coldstream charges and
// no one has stated it — the same reason the live site's "$11,000–$14,000" is not in this repo.
// Also refused: their `serviceArea` property, which schema.org superseded with `areaServed`.
// Copying a competitor's mistake is not benchmarking.
import { MARKET_LIST, NATIONAL, NATIONAL_PHONE, businessId, servicesFor } from "./markets.js";
import { CLAIMS, PROFILES, HOURS } from "./claims.js";
import LASTMOD from "./generated/lastmod.json" with { type: "json" };

export const SITE = "https://coldstreamexteriors.com";
export const SITE_NAME = "Coldstream Exteriors";

/**
 * The default social-share card.
 *
 * IT USED NOT TO EXIST. Every page in the build pointed og:image at /og-default.jpg and no such
 * file was ever in public/ — so every link shared to Facebook, LinkedIn, Slack or iMessage since
 * the first build has rendered as a blank rectangle. Nothing caught it because the contrast gate
 * only measures hero media and the link checker only reads href, not meta content. There is now a
 * gate for it (verify-build §13).
 *
 * The file is generated by scripts/build-og-image.mjs from the brand tokens, so it repaints when
 * the brand does rather than being a JPEG somebody exported once.
 */
export const OG = {
  image: "/og-default.jpg",
  width: 1200,
  height: 630,
  alt: "Coldstream Exteriors — roofing, siding, windows and gutters in Cincinnati, Columbus and St. Louis",
  locale: "en_US",
};

/**
 * Robots directives for pages that ARE indexable.
 *
 * `max-image-preview:large` is the one that earns its place: without it Google may show a thumbnail
 * or no image at all beside the result, and this is a trade where the photograph of the finished
 * roof is the argument. `max-snippet:-1` and `max-video-preview:-1` remove the length caps Google
 * otherwise applies by default in some regions.
 *
 * This is NOT a substitute for the noindex tag and does not appear on noindexed pages — a page
 * carrying both would be telling a crawler to keep out and to show a large preview.
 */
export const ROBOTS_INDEXABLE = "index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1";

/**
 * The `sameAs` array — every profile that is the same real-world business as this site.
 *
 * Assembled rather than written out, so an entry cannot be added without going through the claims
 * gate, and so the BBB URL is the one `CLAIMS.bbb` already carries instead of a second copy of it.
 * Empty is a legal answer: the property is omitted entirely rather than emitted as [].
 */
export const sameAs = () => {
  const out = PROFILES.map((p) => p.url);
  if (CLAIMS.bbb?.profileUrl) out.push(CLAIMS.bbb.profileUrl);
  return out;
};

/**
 * Hours, in schema shape, or nothing.
 *
 * `HOURS` is null until someone states them — see claims.js. This returns an empty object so a
 * caller can spread it unconditionally and get no property at all, which is the difference between
 * "we have not said" and "we are never open".
 */
const hoursNode = () =>
  HOURS ? { openingHoursSpecification: { "@type": "OpeningHoursSpecification", ...HOURS } } : {};

/**
 * `telephone` for schema, which is NOT the same string as an href.
 *
 * THIS WAS A REAL BUG. Every business node on the site emitted `"telephone": "tel:+15132580450"` —
 * the href, passed straight through from markets.js's `telHref`. schema.org expects a phone
 * NUMBER; a `tel:` URI in that slot is a parse failure that costs the property silently, which is
 * why it survived four rounds of review. The displayed number is used, matching what the page
 * prints and what the GBP listing has to match.
 */
const phone = (market) => market.phone ?? NATIONAL_PHONE;

/** The company's own logo, absolute — schema wants a resolvable URL, not a site-root path. */
export const LOGO = `${SITE}/logo-coldstream-exteriors.jpg`;

/**
 * The service catalogue for one market, as an OfferCatalog.
 *
 * WHY IT IS WORTH HAVING. It is the only machine-readable statement that this business does these
 * four things IN THIS CITY, with a URL for each — the same relationship the services grid states
 * in HTML. It is built from `servicesFor(market)`, so a market that does not run commercial
 * roofing does not claim it here either, which is the same rule the grid and the nav follow.
 */
const offerCatalog = (market) => ({
  hasOfferCatalog: {
    "@type": "OfferCatalog",
    name: `Roofing and exterior services in ${market.name}`,
    itemListElement: servicesFor(market).map((s) => ({
      "@type": "Offer",
      itemOffered: {
        "@type": "Service",
        name: `${s.label} in ${market.name}`,
        url: `${SITE}/${market.slug}/${s.key}/`,
      },
    })),
  },
});

/** The stable identifier for the company itself, as distinct from any one office. */
export const ORG_ID = `${SITE}/#organization`;

/**
 * The reference the NATIONAL service pages use as their `provider`.
 *
 * It carries the `@id` and nothing else that could drift. Before round 42 three templates each
 * wrote out `{ "@type": "Organization", name, url }` with no identifier, so a crawler had no way
 * to know the provider of the roofing service was the same business described on the home page —
 * it read as a fourth, nameless-but-similar company. The market templates already did this right
 * via `providerRef`, which points at the market's own @id.
 */
export const orgRef = () => ({ "@type": "Organization", "@id": ORG_ID, name: SITE_NAME, url: `${SITE}/` });

/**
 * When a page's content last changed, ISO 8601, or null.
 *
 * Computed from git by scripts/build-lastmod.mjs — read that file for exactly what it counts.
 * NULL IS A REAL ANSWER and every caller drops the field rather than substituting today's date;
 * a `dateModified` that moves on every build is worse than no `dateModified` at all, because it
 * trains a crawler to disbelieve the one on the page that really did change.
 */
export const lastModified = (path) => LASTMOD.pages?.[path] ?? null;

/**
 * THE PLACES THIS BUSINESS WORKS, AS ENTITIES RATHER THAN STRINGS.
 *
 * `{ "@type": "City", "name": "Columbus" }` is a string in a box. There are Columbuses in Ohio,
 * Georgia, Indiana, Mississippi and Nebraska, and the site's own geo-detection code already carries
 * a comment about exactly that ambiguity — it refuses to route a Columbus, Georgia visitor to a
 * Central Ohio roofing page. The schema was making the mistake the JavaScript was careful about.
 *
 * A Wikidata ID removes the ambiguity for any machine reading the page — a search crawler, an
 * answer engine, a model summarising the site. It is the difference between telling a reader the
 * name of a place and telling it WHICH place.
 *
 * VERIFIED AGAINST WIKIDATA 2026-08-21, by label and description, not from memory:
 *   Q43196  Cincinnati  "city in and seat of Hamilton County, Ohio, United States"
 *   Q16567  Columbus    "capital city of the U.S. state of Ohio and seat of Franklin County"
 *   Q38022  St. Louis   "independent city in Missouri, United States"
 *   Q1397   Ohio        "state of the United States of America"
 *   Q1581   Missouri    "state of the United States of America"
 *
 * ONLY THE THREE METROS AND TWO STATES ARE HERE. The 77 served towns are not, and should not be
 * guessed at in bulk: "Milford" alone is a town in Ohio, Connecticut, Delaware, Massachusetts,
 * Michigan, Nebraska, New Hampshire and Pennsylvania, and a wrong Wikidata ID is a worse statement
 * than no ID — it actively asserts the wrong place. Adding one means looking it up, like these.
 */
const WIKIDATA = {
  Cincinnati: "Q43196",
  Columbus: "Q16567",
  "St. Louis": "Q38022",
};

const STATE_ENTITY = {
  OH: { name: "Ohio", id: "Q1397" },
  MO: { name: "Missouri", id: "Q1581" },
};

/** A served place, with its Wikidata identity where we have verified one. */
export const placeNode = (name) => WIKIDATA[name]
  ? { "@type": "City", name, sameAs: `https://www.wikidata.org/wiki/${WIKIDATA[name]}` }
  : { "@type": "City", name };

/**
 * Everywhere a market serves, as entities — the metro itself first, then its towns.
 *
 * THE METRO WAS MISSING. `servedAreas` lists the surrounding towns, so Cincinnati's own areaServed
 * named 24 suburbs and not Cincinnati, on a page titled "Roofing in Cincinnati". The metro is also
 * the one name in the list carrying a Wikidata ID, which is what makes it unambiguous.
 */
export const servedPlaces = (market) => [
  placeNode(market.name),
  ...market.servedAreas.filter((a) => a !== market.name).map(placeNode),
];

/** The state a market sits in, as an entity. Used as the market node's containing place. */
export const stateNode = (market) => {
  const st = STATE_ENTITY[market.office?.state];
  return st ? { "@type": "State", name: st.name, sameAs: `https://www.wikidata.org/wiki/${st.id}` } : null;
};

/**
 * The WebSite node — one per site, referenced by every page.
 *
 * It is what makes `isPartOf` on a WebPage resolve to something. Without it a crawler has 75 pages
 * and no statement that they are one site under one publisher.
 */
export const webSiteNode = () => ({
  "@type": "WebSite",
  "@id": `${SITE}/#website`,
  url: `${SITE}/`,
  name: SITE_NAME,
  publisher: { "@id": ORG_ID },
  inLanguage: "en-US",
});

/**
 * The WebPage node — one per page, and the hub the rest of that page's graph hangs off.
 *
 * WHY IT IS WORTH THE BYTES. Before this, a page emitted two or three disconnected JSON-LD blocks:
 * a breadcrumb here, a Service there, an FAQ in a third. Nothing said they described the same page,
 * and nothing tied any of them to the page's own URL, title or publisher. A reader — a crawler, an
 * answer engine, a model asked "what does this company do in Columbus" — had to infer the join.
 *
 * Now every page states it: this URL is a WebPage, it is part of that WebSite, it is about that
 * Organization, its breadcrumb is that BreadcrumbList, and it was last changed on this date.
 */
export const webPageNode = ({ canonical, title, description, breadcrumbId, ogImage }) => {
  const url = new URL(canonical, SITE).href;
  const modified = lastModified(canonical);
  return {
    "@type": "WebPage",
    "@id": `${url}#webpage`,
    url,
    name: title,
    description,
    isPartOf: { "@id": `${SITE}/#website` },
    about: { "@id": ORG_ID },
    inLanguage: "en-US",
    primaryImageOfPage: `${SITE}${ogImage ?? OG.image}`,
    ...(breadcrumbId ? { breadcrumb: { "@id": breadcrumbId } } : {}),
    ...(modified ? { dateModified: modified } : {}),
  };
};

/**
 * The national Organization node.
 *
 * ONE ORGANIZATION, THREE LOCATIONS — not a LocalBusiness. The national page is not a location and
 * must not claim to be one; that ruling predates this file and is unchanged. What is new is the
 * `@id`, which gives the three market nodes something to point `parentOrganization` at. Without it
 * Google sees four unrelated businesses that happen to share a domain.
 */
export const organizationNode = () => ({
  "@context": "https://schema.org",
  "@type": "Organization",
  "@id": ORG_ID,
  name: SITE_NAME,
  url: `${SITE}/`,
  logo: LOGO,
  image: `${SITE}${OG.image}`,
  telephone: phone(NATIONAL),
  sameAs: sameAs(),
  contactPoint: {
    "@type": "ContactPoint",
    contactType: "sales",
    telephone: NATIONAL_PHONE,
    areaServed: ["US-OH", "US-KY", "US-MO"],
    url: `${SITE}/free-estimate/`,
  },
  location: MARKET_LIST.map((m) => ({
    "@type": "RoofingContractor",
    "@id": businessId(m),
    name: `${SITE_NAME} — ${m.name}`,
    url: `${SITE}/${m.slug}/`,
    telephone: phone(m),
    address: {
      "@type": "PostalAddress",
      streetAddress: m.office.street, addressLocality: m.office.city,
      addressRegion: m.office.state, postalCode: m.office.zip, addressCountry: "US",
    },
  })),
});

/**
 * The one LocalBusiness node for one market, for that market's landing page.
 *
 * Still the only place each address is written — service hubs and location pages reference this
 * `@id` rather than restating the NAP, and that rule is what the address gate in verify-build
 * enforces. Everything added here is a property of the same node, not a second node.
 */
export const businessNode = (market) => ({
  "@context": "https://schema.org",
  "@type": "RoofingContractor",
  "@id": businessId(market),
  name: `${SITE_NAME} — ${market.name}`,
  url: `${SITE}/${market.slug}/`,
  parentOrganization: { "@id": ORG_ID },
  telephone: phone(market),
  logo: LOGO,
  image: `${SITE}${OG.image}`,
  address: {
    "@type": "PostalAddress",
    streetAddress: market.office.street, addressLocality: market.office.city,
    addressRegion: market.office.state, postalCode: market.office.zip, addressCountry: "US",
  },
  // NO `sameAs` ON A MARKET NODE, DELIBERATELY. The profiles in claims.js belong to the company:
  // the BBB record is filed in Cincinnati, and one Facebook page covers all three metros. Copying
  // the company's list onto the St. Louis office would assert that a Cincinnati BBB profile is the
  // St. Louis business, which is the entity-merging mistake `sameAs` is easiest to make. The
  // parentOrganization link above already tells a crawler where to find them.
  //
  // What DOES belong here is each market's own Google Business Profile URL, one per office. Those
  // are the missing piece — see claims.js PROFILES.
  ...hoursNode(),
  areaServed: servedPlaces(market),
  ...(stateNode(market) ? { containedInPlace: stateNode(market) } : {}),
  ...offerCatalog(market),
});
